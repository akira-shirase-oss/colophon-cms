#!/usr/bin/env bash
# Rebuilds the load-case table docs/BENCHMARKS.md carries, from the evidence store.
# For each case L01-L14 the newest HELD run in perf/results/history.jsonl becomes a row
# with the numbers the report cites; a case no stored run has held prints "owed".
#
#   scripts/benchmark-report.sh            print the markdown table
#   scripts/benchmark-report.sh --check    also fail when a case is owed or its artifact
#                                          file is missing from perf/results/
#
# The script only reads the evidence store and prints markdown: it never edits the doc
# (the numbers in docs/BENCHMARKS.md are regenerated by pasting this output), and it
# refuses to name a run whose artifact file is gone rather than quote it silently.
set -euo pipefail
cd "$(dirname "$0")/.."

check=0
[[ "${1:-}" == "--check" ]] && check=1

history=perf/results/history.jsonl
[[ -f $history ]] || { echo "error: $history is missing" >&2; exit 1; }
command -v jq >/dev/null || { echo "error: jq is required" >&2; exit 1; }

status=0
held_count=0
owed_count=0
missing_count=0

echo "| Case | Scenario | Evidence run (perf/results/) | Requests | Req/s | p95 ms | p99 ms |"
echo "|---|---|---|---:|---:|---:|---:|"

for n in 01 02 03 04 05 06 07 08 09 10 11 12 13 14; do
  case="l$n"
  # The newest stored run whose own verdict held. `// empty` would swallow a computed
  # held:false, so the filter reads it raw; the pick is by the record's own date.
  record=$(jq -cs --arg l "$case" \
    '[.[] | select(.[$l] != null and .[$l].held == true)] | sort_by(.date) | last // empty' \
    "$history")
  if [[ -z $record ]]; then
    echo "| $(tr '[:lower:]' '[:upper:]' <<<"$case") | owed | - | - | - | - | - |"
    owed_count=$(( owed_count + 1 ))
    continue
  fi
  endpoint=$(jq -r '.endpoint' <<<"$record")
  scenario=$(jq -r '.scenario' <<<"$record")
  stamp=$(jq -r '.date | gsub(":"; "")' <<<"$record")
  machine=$(jq -r '.machine.id' <<<"$record")
  # The filename shape scripts/load.sh writes, including a cluster run's shape suffix.
  shape=""
  if jq -e '.topology.balancer != null' <<<"$record" >/dev/null; then
    shape="-cluster$(jq -r '.topology | "\(.servers)s\(.workers)w"' <<<"$record")"
  fi
  file="${stamp}-${endpoint}-${scenario}-${machine}${shape}.json"
  if [[ ! -f "perf/results/$file" ]]; then
    echo "warn: index names $file, but it is not in perf/results/" >&2
    file="MISSING: $file"
    missing_count=$(( missing_count + 1 ))
    status=1
  fi
  held_count=$(( held_count + 1 ))
  jq -r --arg c "$(tr '[:lower:]' '[:upper:]' <<<"$case")" --arg f "$file" \
    '"| \($c) | \(.endpoint) \(.scenario) | \($f) | \(.requests) | \(.rps) | \(.latency_ms.p95) | \(.latency_ms.p99) |"' \
    <<<"$record"
done

echo
echo "$held_count held, $owed_count owed${missing_count:+, $missing_count missing artifacts} (index: $history)"

if (( check == 1 && (owed_count > 0 || missing_count > 0) )); then
  status=1
fi
exit "$status"
